import json

from indicators import (
    calculate_current_ema23,
    calculate_ema_filter
)


# ==================================================
# 設定
# ==================================================

STOCK = "2330"


# ==================================================
# 讀取 history.json
# ==================================================

with open(
    "history.json",
    "r",
    encoding="utf-8"
) as f:

    history = json.load(f)


# ==================================================
# 取得30分K
# ==================================================

candles = history[
    "30m"
][
    STOCK
]


# ==================================================
# 取得已完成30分K Close
# ==================================================

closes = [
    candle["close"]
    for candle in candles
]


# ==================================================
# 測試用目前價格
#
# 先直接使用最後一根30分K的 Close
# ==================================================

current_price = closes[-1]


# ==================================================
# 計算 EMA23
# ==================================================

ema23 = calculate_current_ema23(
    closes[:-1],
    current_price
)


# ==================================================
# 計算 EMA23 ±2% 濾網
# ==================================================

ema_up, ema_dw = calculate_ema_filter(
    ema23
)


# ==================================================
# 顯示結果
# ==================================================

print("=" * 40)

print("2330 EMA23 濾網測試")

print("=" * 40)

print(
    f"30分K數量: {len(candles)}"
)

print(
    f"目前價格: {current_price:g}"
)

print(
    f"EMA23: {ema23:.4f}"
)

print(
    f"EMA23 +2%: {ema_up:.4f}"
)

print(
    f"EMA23 -2%: {ema_dw:.4f}"
)

print("=" * 40)